export function roleHasPermission(
  role: string | null | undefined,
  permission: EventPermission,
): boolean {
  if (!role) {
    return false;
  }

  const permissions = ROLE_PERMISSIONS[role as EventRole];
  return permissions ? permissions.includes(permission) : false;
}
