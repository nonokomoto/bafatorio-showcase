#!/bin/bash

# 📚 Example: Complete Schema Change Workflow
# This demonstrates the recommended workflow for safe schema changes

echo "🚀 SAFE SCHEMA CHANGE WORKFLOW EXAMPLE"
echo "======================================"
echo ""

echo "📋 Step 1: Check current state"
echo "------------------------------"
echo "Before making any changes, let's see what we have:"
echo ""

if [ -f "amplify_outputs.json" ]; then
    REGION=$(grep -o '"aws_region":"[^"]*"' amplify_outputs.json | cut -d'"' -f4)
    echo "✅ AWS Region: $REGION"
    
    # Show current tables (if AWS CLI is configured)
    if aws sts get-caller-identity &> /dev/null; then
        echo "✅ AWS CLI configured"
        echo ""
        echo "Current DynamoDB tables:"
        aws dynamodb list-tables --region "$REGION" --output table 2>/dev/null || echo "   (Unable to list tables - check permissions)"
    else
        echo "⚠️  AWS CLI not configured - run 'aws configure' first"
    fi
else
    echo "❌ amplify_outputs.json not found - make sure you're in the project root"
fi

echo ""
echo "📦 Step 2: Create backup BEFORE schema changes"
echo "----------------------------------------------"
echo "This is the MOST IMPORTANT step!"
echo ""
echo "Run this command:"
echo "   ./scripts/backup-dev-tables.sh"
echo ""
echo "What this does:"
echo "   • Discovers your dev/sandbox tables"
echo "   • Backs up all data to timestamped files"
echo "   • Creates manifest with metadata"
echo "   • Shows progress and summary"
echo ""

echo "🔧 Step 3: Make your schema changes"
echo "-----------------------------------"
echo "Now you can safely edit your schema:"
echo ""
echo "   1. Edit amplify/data/resource.ts"
echo "   2. Make your changes (add fields, modify enums, etc.)"
echo "   3. Save the file"
echo ""

echo "🚀 Step 4: Deploy schema changes"
echo "--------------------------------"
echo "Deploy your changes to sandbox:"
echo ""
echo "   npx ampx sandbox"
echo ""
echo "⚠️  This might recreate tables and lose data!"
echo "   (That's why we made the backup in Step 2)"
echo ""

echo "🔍 Step 5: Check if data was preserved"
echo "--------------------------------------"
echo "After deployment, check your tables:"
echo ""
echo "   • Go to AWS Console → DynamoDB"
echo "   • Check your tables for data"
echo "   • If data is missing, don't panic!"
echo ""

echo "🔄 Step 6: Restore if needed"
echo "----------------------------"
echo "If data was lost during schema change:"
echo ""
echo "   1. List available backups:"
echo "      ./scripts/restore-dev-tables.sh"
echo ""
echo "   2. Restore from latest backup:"
echo "      ./scripts/restore-dev-tables.sh [timestamp]"
echo ""
echo "   Example:"
echo "      ./scripts/restore-dev-tables.sh 20250523_145228"
echo ""

echo "✅ Step 7: Verify restoration"
echo "-----------------------------"
echo "After restoration, verify your data:"
echo ""
echo "   • Check AWS Console → DynamoDB"
echo "   • Test your application"
echo "   • Verify all data is restored correctly"
echo ""

echo "🎯 BEST PRACTICES SUMMARY"
echo "========================="
echo ""
echo "✅ DO:"
echo "   • Always backup before schema changes"
echo "   • Test schema changes in dev first"
echo "   • Keep backups organized by timestamp"
echo "   • Document what changes you made"
echo "   • Share backup timestamps with team"
echo ""
echo "❌ DON'T:"
echo "   • Skip the backup step (never!)"
echo "   • Make multiple schema changes at once"
echo "   • Delete backups immediately"
echo "   • Test experimental changes on production"
echo ""

echo "🚨 EMERGENCY RECOVERY"
echo "====================="
echo ""
echo "If you already lost data and didn't backup:"
echo ""
echo "   1. Check if Point-in-Time Recovery is enabled:"
echo "      AWS Console → DynamoDB → Table → Backups"
echo ""
echo "   2. Look for any manual backups"
echo ""
echo "   3. Check application logs for data"
echo ""
echo "   4. Contact team members for data exports"
echo ""
echo "   5. As last resort, recreate test data"
echo ""

echo "📞 NEED HELP?"
echo "============="
echo ""
echo "   • Read: scripts/README.md"
echo "   • Check: AWS CloudWatch logs"
echo "   • Review: Git commit history"
echo "   • Ask: Team members for backup timestamps"
echo ""

echo "🎉 You're now ready for safe schema changes!"
echo "" 